// Generates src/styles/tokens.css (Tailwind v4 @theme) and src/lib/textStyles.ts from FigCraft exports:
//   design/variables.css  ← FigCraft run_command variable.export {format: "tailwind", path: <abs>/design/variables.css}
//                           (optional: a design without variables has none)
//   design/styles.json    ← FigCraft run_command style.list {} saved as JSON (paint, text and effect styles)
// Run: npm run tokens
//
// Variable names are kept exactly as FigCraft exports them, so the theme utilities in inspect.code output
// (bg-…, text-…, rounded-…) are valid here. Adjust CONFIG for the project; never edit tokens.css by hand.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const slug = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')

const CONFIG = {
  // Text style name → utility name: "Body/SM/Regular" → text-body-sm-regular.
  textName: (name) => slug(name),
  // Paint style name → colour token: "Blue Zodiac/500" → bg-blue-zodiac-500, text-blue-zodiac-500.
  colorName: (name) => slug(name),
  // Families whose fallback should be serif rather than sans-serif.
  serif: ['Gloock'],
  // Font stack per family. Fontsource registers variable fonts as "<Family> Variable".
  fontStack: (family) =>
    CONFIG.serif.includes(family)
      ? `'${family} Variable', '${family}', ui-serif, Georgia, serif`
      : `'${family} Variable', '${family}', ui-sans-serif, system-ui, sans-serif`,
  // Family behind --font-sans (the page default). null: the family with the most text styles.
  sansFamily: 'Plus Jakarta Sans',
}

const root = new URL('../', import.meta.url)
const read = (p) => readFileSync(new URL(p, root), 'utf8')
const styles = JSON.parse(read('design/styles.json'))
const variablesCss = existsSync(new URL('design/variables.css', root))
  ? read('design/variables.css')
      .replace(/^@import .*;\s*$/gm, '')
      .trim()
  : ''

const warnings = []
const out = []
const line = (s = '') => out.push(s)
const round = (n, d = 4) => +n.toFixed(d)
const rem = (px) => `${round(px / 16)}rem`
const channel = (v) => Math.round(v * 255)
const hex = ({ r, g, b }) =>
  '#' + [r, g, b].map((v) => channel(v).toString(16).padStart(2, '0')).join('')
const rgba = (c, opacity = 1) => {
  const a = round((c.a ?? 1) * opacity, 3)
  return a >= 1 ? hex(c) : `rgb(${channel(c.r)} ${channel(c.g)} ${channel(c.b)} / ${a})`
}

const WEIGHTS = {
  thin: 100,
  hairline: 100,
  extralight: 200,
  ultralight: 200,
  light: 300,
  regular: 400,
  normal: 400,
  book: 400,
  medium: 500,
  semibold: 600,
  demibold: 600,
  bold: 700,
  extrabold: 800,
  ultrabold: 800,
  black: 900,
  heavy: 900,
}
const weightOf = (fontStyle) => {
  const key = fontStyle.toLowerCase().replace(/italic|oblique|\s|-/g, '') || 'regular'
  if (!(key in WEIGHTS)) warnings.push(`unknown font style "${fontStyle}", using 400`)
  return WEIGHTS[key] ?? 400
}

const paints = styles.filter((s) => s.type === 'paint')
const texts = styles.filter((s) => s.type === 'text')
const effects = styles.filter((s) => s.type === 'effect')

// Variables first: their colour names must not be shadowed by paint styles of the same name.
const variableColors = new Set([...variablesCss.matchAll(/--color-([\w-]+)\s*:/g)].map((m) => m[1]))

line('/* AUTO-GENERATED by scripts/build-tokens.mjs. Do not edit by hand; run `npm run tokens`. */')
line('/* Source: FigCraft variables (design/variables.css) and styles (design/styles.json). */')
line()
line('@theme {')
line('  /* Only design-system colours exist: the default Tailwind palette is removed. */')
line('  --color-*: initial;')
line('  --color-transparent: transparent;')
line('  --color-current: currentColor;')
line('}')
if (variablesCss) {
  line()
  line(
    '/* FigCraft variables, as variable.export {format: "tailwind"} writes them (modes included). */',
  )
  line(variablesCss)
}
line()
line('@theme {')

// Paint styles → colours
const colorLines = []
for (const s of paints) {
  const visible = (s.paints ?? []).filter((p) => p.visible !== false)
  const name = CONFIG.colorName(s.name)
  if (visible.length !== 1 || visible[0].type !== 'solid') {
    warnings.push(
      `paint style "${s.name}" is not one solid paint (gradient or stack): add it by hand`,
    )
    continue
  }
  if (variableColors.has(name)) {
    warnings.push(`paint style "${s.name}" has the same name as a variable: the variable wins`)
    continue
  }
  colorLines.push(`  --color-${name}: ${rgba(visible[0].color, visible[0].opacity ?? 1)};`)
}
if (colorLines.length) {
  line('  /* Paint styles → bg-*, text-*, border-* … */')
  colorLines.forEach((l) => line(l))
  line()
}

// Fonts
const families = new Map()
for (const s of texts) {
  const f = s.style.font_family
  families.set(f, (families.get(f) ?? 0) + 1)
}
const sans = CONFIG.sansFamily ?? [...families].sort((a, b) => b[1] - a[1])[0]?.[0]
if (families.size) {
  line('  /* Font families → font-<family>; --font-sans is the page default. */')
  if (sans) line(`  --font-sans: ${CONFIG.fontStack(sans)};`)
  for (const f of families.keys()) line(`  --font-${slug(f)}: ${CONFIG.fontStack(f)};`)
  line()
}

// Text styles → text-<name> (size, line height, tracking and weight in one utility)
const textNames = []
if (texts.length) {
  line('  /* Text styles → text-<name>. Add font-<family> where the family is not --font-sans. */')
  for (const s of texts) {
    const t = s.style
    const name = CONFIG.textName(s.name)
    textNames.push(name)
    const lh =
      t.line_height?.unit === 'pixels'
        ? rem(t.line_height.value)
        : t.line_height?.unit === 'percent'
          ? // FigCraft lays percentage line heights out on whole pixels (14 px × 190 % → 27, not
            // 26.6): a five-line paragraph would otherwise come out 1.6 px shorter than the frame.
            rem(Math.round((t.font_size * t.line_height.value) / 100))
          : 'normal'
    const ls =
      t.letter_spacing?.unit === 'pixels'
        ? `${round(t.letter_spacing.value, 3)}px`
        : `${round((t.letter_spacing?.value ?? 0) / 100, 4)}em`
    const extra = [
      t.font_family !== sans && `font-${slug(t.font_family)}`,
      /italic|oblique/i.test(t.font_style) && 'italic',
      t.case && t.case !== 'original' && `case: ${t.case}`,
      t.decoration && t.decoration !== 'none' && `decoration: ${t.decoration}`,
    ].filter(Boolean)
    line(
      `  /* ${s.name} · ${t.font_family} ${t.font_style} ${t.font_size}px${extra.length ? ' · ' + extra.join(', ') : ''} */`,
    )
    line(`  --text-${name}: ${rem(t.font_size)};`)
    line(`  --text-${name}--line-height: ${lh};`)
    line(`  --text-${name}--letter-spacing: ${ls};`)
    line(`  --text-${name}--font-weight: ${weightOf(t.font_style)};`)
  }
  line()
}

// Effect styles → shadow-<name>
const shadowType = (e) =>
  String(e.type ?? '')
    .toLowerCase()
    .replace(/[_\s]/g, '')
const effectLines = []
for (const s of effects) {
  const list = (s.effects ?? []).filter((e) => e.visible !== false)
  const shadows = list.filter((e) => ['dropshadow', 'innershadow'].includes(shadowType(e)))
  if (shadows.length !== list.length)
    warnings.push(`effect style "${s.name}" has blurs or other effects: add those by hand`)
  if (!shadows.length) continue
  const parts = shadows.map((e) => {
    const x = e.offset?.x ?? e.offsetX ?? e.x ?? 0
    const y = e.offset?.y ?? e.offsetY ?? e.y ?? 0
    const inset = shadowType(e) === 'innershadow' ? 'inset ' : ''
    return `${inset}${x}px ${y}px ${e.radius ?? 0}px ${e.spread ?? 0}px ${rgba(e.color ?? { r: 0, g: 0, b: 0, a: 0.25 })}`
  })
  effectLines.push(`  --shadow-${slug(s.name).replace(/^shadow-/, '')}: ${parts.join(', ')};`)
}
if (effectLines.length) {
  line('  /* Effect styles → shadow-<name> */')
  effectLines.forEach((l) => line(l))
  line()
}

line('  /* Layout: set from the design grid (frame width, content width). */')
line('  --container-frame: 90rem; /* 1440 px desktop frame */')
line('}')

writeFileSync(new URL('src/styles/tokens.css', root), out.join('\n') + '\n')
writeFileSync(
  new URL('src/lib/textStyles.ts', root),
  '// AUTO-GENERATED by scripts/build-tokens.mjs: the text-<name> utilities, so cn() treats them as font sizes.\n' +
    `export const TEXT_STYLES: string[] = ${JSON.stringify(textNames, null, 2)}\n`,
)

console.log(
  `tokens.css: ${variableColors.size} colour variables, ${colorLines.length} paint styles, ${families.size} font families, ${texts.length} text styles, ${effectLines.length} shadows`,
)
for (const w of warnings) console.warn(`warning: ${w}`)
