// Generates src/assets/images/index.ts: one typed entry per photo with src, srcSet and
// intrinsic size, from the WebP files in src/assets/images/**/<name>-{sm,lg}.webp.
// Run after adding or replacing photos: npm run images
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../src/assets/images', import.meta.url))

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f)
    return statSync(p).isDirectory() ? walk(p) : p.endsWith('.webp') ? [p] : []
  })
}

// Width/height from the WebP header (VP8, VP8L and VP8X chunks).
function webpSize(file) {
  const b = readFileSync(file)
  const chunk = b.toString('ascii', 12, 16)
  if (chunk === 'VP8X') return { width: 1 + b.readUIntLE(24, 3), height: 1 + b.readUIntLE(27, 3) }
  if (chunk === 'VP8L') {
    const bits = b.readUInt32LE(21)
    return { width: (bits & 0x3fff) + 1, height: ((bits >> 14) & 0x3fff) + 1 }
  }
  if (chunk === 'VP8 ')
    return { width: b.readUInt16LE(26) & 0x3fff, height: b.readUInt16LE(28) & 0x3fff }
  throw new Error(`Unrecognised WebP: ${file}`)
}

const camel = (s) => s.replace(/[-/](\w)/g, (_, c) => c.toUpperCase())

const groups = new Map()
for (const file of walk(root)) {
  const rel = relative(root, file).replaceAll('\\', '/')
  const m = rel.match(/^(.*)-(sm|lg)\.webp$/)
  if (!m) continue
  const [, name, size] = m
  if (!groups.has(name)) groups.set(name, {})
  groups.get(name)[size] = { rel, ...webpSize(file) }
}

const imports = []
const entries = []
for (const name of [...groups.keys()].sort()) {
  const g = groups.get(name)
  const id = camel(name)
  const variants = ['sm', 'lg'].filter((s) => g[s])
  for (const s of variants) imports.push(`import ${id}_${s} from './${g[s].rel}'`)
  const largest = g.lg ?? g.sm
  const srcSet = variants.map((s) => `\${${id}_${s}} ${g[s].width}w`).join(', ')
  entries.push(
    `  ${id}: { src: ${id}_${g.lg ? 'lg' : 'sm'}, srcSet: \`${srcSet}\`, width: ${largest.width}, height: ${largest.height} },`,
  )
}

const out = `// AUTO-GENERATED by scripts/build-images.mjs. Do not edit; run \`npm run images\`.
${imports.join('\n')}

export type ImageAsset = { src: string; srcSet: string; width: number; height: number }

export const images = {
${entries.join('\n')}
} satisfies Record<string, ImageAsset>

export type ImageName = keyof typeof images
`
writeFileSync(join(root, 'index.ts'), out)
console.log(`images/index.ts: ${groups.size} images`)
